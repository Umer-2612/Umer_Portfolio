/** Puts a company's logo in front of its name wherever the name appears in a string. */
export function withBrand(text: string): ReactNode[] {
  return text.split(/(Apple|WebOsmotic)/g).map((part, i) => {
    if (part === "Apple" || part === "WebOsmotic") {
      return (
        <span key={i} className="brand-word">
          {part === "Apple" ? <AppleMark /> : <WebOsmoticMark />}
          {part}
        </span>
      );
    }
    return <span key={i}>{part}</span>;
  });
}

/** Click handler for in-site links: swaps the page without a reload, but lets Cmd/Ctrl/Shift-click and middle-click open a new tab. */
export function navClick(go: (id: PageId) => void, id: PageId) {
  return (e: MouseEvent<HTMLAnchorElement>) => {
    if (e.defaultPrevented || e.button !== 0 || e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return;
    e.preventDefault();
    go(id);
  };
}
